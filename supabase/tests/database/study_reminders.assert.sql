begin;
do $$
declare
 uid uuid := 'dd000000-0000-4000-8000-000000000001';
 other_uid uuid := 'dd000000-0000-4000-8000-000000000002';
 tz text; c jsonb; claim jsonb; retry jsonb; did uuid := extensions.gen_random_uuid();
 token uuid; rev text;
begin
 assert not has_function_privilege('anon','public.mpk_get_reminder_preferences()','execute');
 assert not has_function_privilege('authenticated','public.mpk_claim_reminder(jsonb,text,jsonb,uuid,text)','execute');
 assert not has_function_privilege('authenticated','public.mpk_reminder_candidates()','execute');
 assert not has_function_privilege('authenticated','public.mpk_reminder_metrics()','execute');
 assert not has_function_privilege('authenticated','public.mpk_unsubscribe_reminders(uuid,uuid)','execute');
 assert not has_table_privilege('authenticated','private.study_reminder_deliveries','select');
 assert not has_table_privilege('authenticated','private.study_reminder_preferences','update');
 assert has_function_privilege('service_role','public.mpk_claim_reminder(jsonb,text,jsonb,uuid,text)','execute');
 insert into auth.users(id,email,created_at,email_confirmed_at,raw_user_meta_data) values
 (uid,'reminders@example.test',now()-interval '10 days',now()-interval '10 days','{"first_name":"Reminder","last_name":"Test"}'),
 (other_uid,'other@example.test',now()-interval '10 days',null,'{"first_name":"Other","last_name":"Test"}');
 assert (select enabled and time_zone='America/Toronto' from private.study_reminder_preferences where user_id=uid), 'New accounts initialized';
 perform set_config('request.jwt.claim.sub',uid::text,true);
 assert public.mpk_get_reminder_preferences()->>'enabled'='true';
 begin perform public.mpk_update_reminder_preferences(true,'Invalid/Zone',true,null); raise exception 'Invalid timezone allowed';
 exception when invalid_parameter_value then null; end;
 select name into tz from pg_catalog.pg_timezone_names where extract(hour from now() at time zone name)=18 order by name limit 1;
 perform public.mpk_update_reminder_preferences(true,tz,true,null);
 perform public.mpk_record_study_visit('America/Vancouver');
 assert (select time_zone=tz from private.study_reminder_preferences where user_id=uid), 'Manual override retained';
 update private.study_reminder_preferences set last_seen_at=now()-interval '5 days' where user_id=uid;
 c:=private.study_reminder_context(uid);
 assert public.mpk_claim_reminder(c,'inactive','{"text":"frozen"}',did) is null, 'Disabled by default';
 update private.study_reminder_control set enabled=true where id;
 update auth.users set last_sign_in_at=now() where id=uid;
 assert public.mpk_claim_reminder(private.study_reminder_context(uid),'inactive','{}',did) is null, 'Recent sign-in suppresses';
 update auth.users set last_sign_in_at=null where id=uid;
 claim:=public.mpk_claim_reminder(private.study_reminder_context(uid),'inactive','{"text":"frozen"}',did);
 assert claim->>'id'=did::text, 'Claim succeeds';
 assert public.mpk_claim_reminder(c,'inactive','{}',extensions.gen_random_uuid()) is null, 'Stale concurrent snapshot cannot send';
 assert public.mpk_claim_reminder(private.study_reminder_context(uid),'inactive','{}',extensions.gen_random_uuid()) is null, 'Active lease cannot be claimed twice';
 assert (select reserved=1 from private.study_reminder_usage where bucket=to_char(now() at time zone 'UTC','YYYY-MM-DD'));
 perform public.mpk_finish_reminder(did,(claim->>'lease')::uuid,'retry',null,'transport_unknown');
 update private.study_reminder_deliveries set retry_at=now()-interval '1 second',lease_until=now()-interval '1 second' where id=did;
 retry:=public.mpk_claim_reminder(private.study_reminder_context(uid),'inactive','{"text":"changed"}',extensions.gen_random_uuid());
 assert retry->>'id'=did::text and retry->'payload'->>'text'='frozen', 'Retries preserve payload and id';
 assert (select reserved=1 from private.study_reminder_usage where bucket=to_char(now() at time zone 'UTC','YYYY-MM-DD')), 'Retry does not reserve again';
 perform public.mpk_finish_reminder(did,(claim->>'lease')::uuid,'sent','old-worker');
 assert (select provider_id is null from private.study_reminder_deliveries where id=did), 'Old worker cannot acknowledge new lease';
 select unsubscribe_version into token from private.study_reminder_preferences where user_id=uid;
 perform public.mpk_update_reminder_preferences(true,tz,true,null);
 assert (select unsubscribe_version=token from private.study_reminder_preferences where user_id=uid), 'Ordinary preference changes keep unsubscribe links valid';
 assert public.mpk_unsubscribe_reminders(uid,token);
 assert (select status='cancelled' from private.study_reminder_deliveries where id=did);
 assert public.mpk_reminder_send_context(did,(retry->>'lease')::uuid) is null;
 assert public.mpk_unsubscribe_reminders(uid,token), 'Repeated unsubscribe is idempotent';
 perform public.mpk_update_reminder_preferences(true,tz,true,null);
 assert not public.mpk_unsubscribe_reminders(uid,token), 'Reenabled preferences invalidate old link';
 assert (select enabled from private.study_reminder_preferences where user_id=other_uid), 'Other account untouched';
 assert public.mpk_claim_reminder(private.study_reminder_context(uid),'inactive','{}',extensions.gen_random_uuid()) is null, 'Cancelled uncertain sends still count';
 delete from private.study_reminder_deliveries where user_id=uid;
 update private.study_reminder_control set daily_budget=1 where id;
 assert public.mpk_claim_reminder(private.study_reminder_context(uid),'inactive','{}',extensions.gen_random_uuid()) is null, 'Daily budget is atomic';
 update private.study_reminder_control set daily_budget=50,monthly_budget=1 where id;
 assert public.mpk_claim_reminder(private.study_reminder_context(uid),'inactive','{}',extensions.gen_random_uuid()) is null, 'Monthly budget is atomic';
 update private.study_reminder_control set monthly_budget=1500,pause_until=now()+interval '1 hour' where id;
 assert public.mpk_claim_reminder(private.study_reminder_context(uid),'inactive','{}',extensions.gen_random_uuid()) is null, 'Provider pause honored';
 update private.study_reminder_control set pause_until=null where id;
 -- Exam notice state survives retention and resets only when the date changes.
 update public.exam_goals set target_date=(now() at time zone tz)::date-1 where user_id=uid;
 c:=private.study_reminder_context(uid); rev:=c->>'goalRevision';
 claim:=public.mpk_claim_reminder(c,'exam_update','{}',extensions.gen_random_uuid());
 assert claim is not null;
 assert (select past_exam_notified=rev from private.study_reminder_preferences where user_id=uid);
 delete from private.study_reminder_deliveries where user_id=uid;
 assert public.mpk_claim_reminder(private.study_reminder_context(uid),'exam_update','{}',extensions.gen_random_uuid()) is null, 'Past date notice is once';
 perform public.mpk_update_reminder_preferences(true,tz,true,(c->>'targetDate')::date);
 assert private.study_reminder_context(uid)->>'goalRevision'=rev, 'Other preferences do not retrigger past notice';
 update public.exam_goals set target_date=null where user_id=uid;
 assert (select past_exam_notified is null from private.study_reminder_preferences where user_id=uid);
 -- Bounces may arrive before the API response, duplicate and out of order.
 claim:=public.mpk_claim_reminder(private.study_reminder_context(uid),'inactive','{}',extensions.gen_random_uuid()); did:=(claim->>'id')::uuid;
 perform public.mpk_reminder_webhook('evt1','email.bounced','provider-1','reminders@example.test',did);
 perform public.mpk_reminder_webhook('evt1','email.bounced','provider-1','reminders@example.test',did);
 perform public.mpk_reminder_webhook('evt2','email.delivered','provider-1','reminders@example.test',did);
 assert (select count(*)=1 from private.study_reminder_events where id='evt1');
 assert (select status='bounced' from private.study_reminder_deliveries where id=did), 'Delivery events cannot undo suppression';
 assert (private.study_reminder_context(uid)->>'suppressed')::boolean;
 update auth.users set email='new-reminders@example.test' where id=uid;
 assert not (private.study_reminder_context(uid)->>'suppressed')::boolean, 'Suppression follows the address';
 update private.study_reminder_deliveries set attempted_at=now()-interval '31 days' where id=did;
 perform public.mpk_reminder_maintenance();
 assert not exists(select 1 from private.study_reminder_deliveries where id=did), 'Delivery data expires in 30 days';
 assert (select reserved>0 from private.study_reminder_usage where bucket=to_char(now() at time zone 'UTC','YYYY-MM')), 'Anonymous monthly counts survive cleanup';
 -- Controlled tests waive only the clock window for the exact named recipient.
 select name into tz from pg_catalog.pg_timezone_names where extract(hour from now() at time zone name)=10 order by name limit 1;
 update private.study_reminder_preferences set time_zone=tz where user_id=other_uid;
 c:=private.study_reminder_context(other_uid);
 assert public.mpk_claim_reminder(c,'inactive','{}',extensions.gen_random_uuid(),'other@example.test') is null, 'Controlled tests still require verification';
 update auth.users set email_confirmed_at=now()-interval '5 days' where id=other_uid;
 c:=private.study_reminder_context(other_uid);
 assert public.mpk_claim_reminder(c,'inactive','{}',extensions.gen_random_uuid()) is null, 'Scheduled sends stay in their local window';
 assert public.mpk_claim_reminder(c,'inactive','{}',extensions.gen_random_uuid(),'wrong@example.test') is null, 'Controlled recipient must match';
 update private.study_reminder_control set daily_budget=0 where id;
 assert public.mpk_claim_reminder(c,'inactive','{}',extensions.gen_random_uuid(),'other@example.test') is null, 'Controlled tests respect quota';
 update private.study_reminder_control set daily_budget=50 where id;
 claim:=public.mpk_claim_reminder(c,'inactive','{}',extensions.gen_random_uuid(),'other@example.test');
 assert claim is not null, 'Controlled test can run outside the delivery window';
 perform public.mpk_finish_reminder((claim->>'id')::uuid,(claim->>'lease')::uuid,'sent','controlled-provider');
 assert public.mpk_claim_reminder(private.study_reminder_context(other_uid),'inactive','{}',extensions.gen_random_uuid(),'other@example.test') is null, 'Controlled test counts toward frequency';
end; $$;
rollback;
